  for (const w of words) if (!COLORS[w]) throw new Error(`color word "${w}" missing from dictionary (${r.a} ${r.rg})`);
  if (!/^L0[123] · s\d+$/.test(r.ref)) throw new Error("bad slideRef " + r.ref);
  let id = `${r.g}-${slug(r.a)}-${slug(r.rg)}-${slug(r.c)}`;
  while (ids.has(id)) id += "-2";
